"use strict";

const test = require("node:test");
const assert = require("node:assert/strict");
const hotspotController = require("../controllers/hotspotController");
const { buildHotspotOnLoginScript } = require("../services/hotspotProfileConfig");

function responseMock() {
  return {
    statusCode: 200,
    body: null,
    status(code) { this.statusCode = code; return this; },
    json(value) { this.body = value; return this; }
  };
}

test("HotSpot on-login preview returns the same V3 script generated by the backend", async () => {
  const req = { body: { name: "30-Day", sharedUsers: 1, validityValue: 30, validityUnit: "days" } };
  const res = responseMock();

  await hotspotController.previewProfileScript(req, res);

  assert.equal(res.statusCode, 200);
  assert.equal(res.body.success, true);
  assert.equal(res.body.scriptVersion, "FAZ_HOTSPOT_EXPIRY_V3");
  assert.equal(res.body.onLogin, buildHotspotOnLoginScript({
    name: "30-Day", sharedUsers: 1, validityValue: 30, validityUnit: "days"
  }));
  assert.match(res.body.onLogin, /get .*uid comment/);
  assert.match(res.body.onLogin, /start-time=23:59:59/);
  assert.doesNotMatch(res.body.onLogin, /interval=30d|FAZ\|PROFILE=/);
});

test("HotSpot on-login preview rejects invalid validity and shared-user inputs", async () => {
  const badValidity = responseMock();
  await hotspotController.previewProfileScript({ body: { name: "Bad", sharedUsers: 1, validityValue: 1.5, validityUnit: "days" } }, badValidity);
  assert.equal(badValidity.statusCode, 400);
  assert.equal(badValidity.body.success, false);

  const badSharedUsers = responseMock();
  await hotspotController.previewProfileScript({ body: { name: "Bad", sharedUsers: 0, validityValue: 1, validityUnit: "days" } }, badSharedUsers);
  assert.equal(badSharedUsers.statusCode, 400);
  assert.equal(badSharedUsers.body.success, false);
});
