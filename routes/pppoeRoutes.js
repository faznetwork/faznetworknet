const express=require("express");
const controller=require("../controllers/pppoeController");
const customerController=require("../controllers/customerController");
const router=express.Router();
const {requireRole}=require("../middleware/rbac");
router.get("/users",controller.users);
router.post("/users",customerController.createCustomer);
router.post("/provision",customerController.createCustomer);
router.get("/profiles",requireRole(["super_admin","admin"]),controller.profiles);
router.get("/active",requireRole(["super_admin","admin"]),controller.active);
router.post("/create-user",controller.createUser);
router.post("/users/create",controller.createUser);
router.post("/update-user",controller.updateUser);
router.post("/toggle-user",controller.toggleUser);
router.post("/kick-user",controller.kickUser);
router.delete("/users/:id",controller.removeUser);
router.post("/create-profile",controller.createProfile);
module.exports=router;